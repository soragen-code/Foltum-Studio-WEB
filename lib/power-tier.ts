export const DEFAULT_POWER_TIER: PowerTier = "MEDIUM";

export function isPowerTier(value: unknown): value is PowerTier {
  return typeof value === "string" && (POWER_TIERS as readonly string[]).includes(value);
}

/** Map legacy Project.tier (minimum/medium/maximum) → power tier. */
export function legacyTierToPower(tier: string | null | undefined): PowerTier {
  switch (tier) {
    case "minimum":
      return "LOW";
    case "maximum":
      return "HIGH";
    case "medium":
      return "MEDIUM";
    default:
      return DEFAULT_POWER_TIER;
  }
}

export function powerToLegacyTier(power: PowerTier): PowerTierConfig["legacyTier"] {
  return POWER_TIER_CONFIG[power].legacyTier;
}

/**
 * Resolve the effective tier for a project. New projects carry `powerTier`;
 * legacy projects only have `tier` — both paths yield the same config.
 */
export function resolvePowerTier(project: {
  powerTier?: string | null;
  tier?: string | null;
}): PowerTierConfig {
  const power = isPowerTier(project.powerTier)
    ? project.powerTier
    : legacyTierToPower(project.tier);
  return POWER_TIER_CONFIG[power];
}

