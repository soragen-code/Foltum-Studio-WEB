/**
 * Power tier — the single source of truth for what the project's "мощность"
 * really controls in the video pipeline.
 *
 * Honest scope (verified against the real Seedance 2.5 schema on Replicate):
 *   - resolution: only "480p" | "720p" exist for Seedance 2.5 (no 1080p)
 *   - baseDuration: the minimal clip length the tier pays for (seconds);
 *     actual clip length is clamped by the scene rules in the video routes
 *   - costPerScene: credits charged per scene clip at baseDuration
 *
 * Anything else (audio, aspect ratio, model) is identical across tiers.
 * Stage 2 must read from here instead of hard-coding numbers.
 */

export type PowerTier = "LOW" | "MEDIUM" | "HIGH";

export const POWER_TIERS: readonly PowerTier[] = ["LOW", "MEDIUM", "HIGH"];

export type SeedanceResolution = "480p" | "720p";

export interface PowerTierConfig {
  id: PowerTier;
  /** Legacy Project.tier value kept in sync for older code paths / dashboard. */
  legacyTier: "minimum" | "medium" | "maximum";
  label: string;
  /** Short UI description (RU) — quality / cost. */
  description: string;
  resolution: SeedanceResolution;
  /** Seconds of clip the base cost covers. */
  baseDuration: number;
  /** Credits per scene clip at baseDuration. */
  costPerScene: number;
}

